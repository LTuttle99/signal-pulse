function entry(
  row: [string, string, string, string?],
  kind: "stock" | "etf",
): Company {
  const [symbol, name, exchange] = row;
  return {
    symbol,
    name,
    exchange,
    kind,
    cik: null,
    aliases:
      kind === "etf"
        ? []
        : symbol === "MSTR"
          ? ["MicroStrategy", "Strategy Inc."]
          : [name],
    sector: kind === "etf" ? "ETF" : "U.S. equities",
    description:
      kind === "etf"
        ? "Exchange-traded fund. View the provider-hosted chart and fund information for this symbol."
        : "U.S.-listed equity. View the provider-hosted price history and financial statements; SEC issuer mapping is not yet configured for this symbol.",
    sourceUrl: `https://www.tradingview.com/symbols/${exchange}-${symbol}/`,
  };
}
